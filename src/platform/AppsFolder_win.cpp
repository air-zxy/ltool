// AppsFolder 那道缝的 Windows 这一份：真去 shell:AppsFolder 里把打包应用列出来。
//
// 用的是 shell 那条正路（SHGetKnownFolderItem + BHID_EnumItems），不是去翻
// C:\Program Files\WindowsApps —— 那个目录的 ACL 连提权的 Administrators 都不给读
//（这台机器实测：glob 它返回空，不报错）。
#include "platform/AppsFolder.h"


#include <windows.h>
#include <shlobj.h>
#include <shobjidl.h>
#include <knownfolders.h>
#include <shlguid.h>

namespace Platform {

namespace {

// 一个 AppsFolder 条目能自报"我的图标从哪儿抽"。拿不到就留空，让上层退到字母图标。
void iconSourceOf(IShellItem* item, QString* src, int* index)
{
    // IShellItem 自己没有 GetIDList —— 这个自由函数才是那条路（它对 CLSID_ShellItem 造出来的
    // 条目都管用，SDK 里写着 "works with objects that support IPersistIDList"）
    LPITEMIDLIST pidl = nullptr;
    if (FAILED(SHGetIDListFromObject(item, &pidl)) || !pidl)
        return;
    IShellFolder* parent = nullptr;
    LPCITEMIDLIST child = nullptr;
    const HRESULT pr = SHBindToParent(pidl, IID_PPV_ARGS(&parent), &child);
    if (SUCCEEDED(pr) && parent) {
        IExtractIconW* ei = nullptr;
        // hwndOwner 要给真窗口：这台实测传 nullptr 时 43 颗一颗图标都拿不到，
        // 换成 GetDesktopWindow() 之后 65 颗里 17 颗拿到了。剩下的还是拿不到
        //（打包应用的图标 handler 不走 IExtractIcon 这条路）—— 那批由上层退到字母图标，不留空白。
        const HRESULT ur = parent->GetUIObjectOf(GetDesktopWindow(), 1, &child, IID_IExtractIconW,
                                                 nullptr, reinterpret_cast<void**>(&ei));
        if (SUCCEEDED(ur) && ei) {
            WCHAR buf[MAX_PATH] = {};
            UINT flags = 0;
            int idx = 0;
            if (SUCCEEDED(ei->GetIconLocation(0, buf, MAX_PATH, &idx, &flags)) && buf[0]) {
                *src = QString::fromWCharArray(buf);
                *index = idx;
            }
            ei->Release();
        }
        parent->Release();
    }
    CoTaskMemFree(pidl);
}

} // namespace

QVector<PackagedApp> packagedApps()
{
    QVector<PackagedApp> out;
    // 这道缝自己负责 COM 初始化：调用方可能是扫描线程（AppScanner::scan 里已经 CoInitializeEx 过），
    // 也可能是主线程直接问一句（判据就是这么调的）—— 不自己兜的话后者会静默列出 0 条，
    // 而 0 条长得和"这台没有打包应用"一模一样，最难查。
    const HRESULT init = CoInitializeEx(nullptr, COINIT_APARTMENTTHREADED);
    const bool weOwnCom = (init == S_OK);   // S_FALSE = 本线程已初始化过，不归我们关
    IShellItem* root = nullptr;
    const HRESULT gr = SHGetKnownFolderItem(FOLDERID_AppsFolder, KF_FLAG_DEFAULT, nullptr,
                                            IID_PPV_ARGS(&root));
    if (FAILED(gr) || !root) {
        if (weOwnCom)
            CoUninitialize();
        return out;   // 这台列不出 AppsFolder（老系统或被策略关掉）：这一类就是零颗，不是没做完
    }
    IEnumShellItems* en = nullptr;
    const HRESULT br = root->BindToHandler(nullptr, BHID_EnumItems, IID_PPV_ARGS(&en));
    if (FAILED(br) || !en) {
        root->Release();
        if (weOwnCom)
            CoUninitialize();
        return out;
    }
    IShellItem* item = nullptr;
    int seen = 0, rejected = 0;
    while (en->Next(1, &item, nullptr) == S_OK && item) {
        ++seen;
        PackagedApp a;
        LPWSTR disp = nullptr;
        LPWSTR parse = nullptr;
        const HRESULT dn = item->GetDisplayName(SIGDN_NORMALDISPLAY, &disp);
        if (SUCCEEDED(dn) && disp) {
            a.name = QString::fromWCharArray(disp);
            CoTaskMemFree(disp);
        }
        const HRESULT dp = item->GetDisplayName(SIGDN_DESKTOPABSOLUTEPARSING, &parse);
        if (SUCCEEDED(dp) && parse) {
            a.launchPath = QString::fromWCharArray(parse);
            CoTaskMemFree(parse);
        }
        // AppsFolder 的子项在 SIGDN_DESKTOPABSOLUTEPARSING 下回来的是**裸 AUMID**
        //（实测这台：`OpenAI.Codex_2p2nqsd0c76g0!App`、`Anysphere.Cursor`），
        // 没有 "shell:AppsFolder\" 那层前缀 —— 前缀得自己拼回去，那才是 ShellExecute 认的写法。
        // 这个虚拟文件夹其实是"整个开始菜单"的合并视图（这台枚举到 312 条，含普通 .lnk 那些），
        // 所以只收"不是文件路径"的那批：带盘符/反斜杠的是快捷方式指向的东西，
        // 上面三个来源已经收过了，不收第二遍。
        const bool isAumid = !a.launchPath.contains(QLatin1Char(':'))
                             && !a.launchPath.contains(QLatin1Char('\\'));
        // 别拿"有没有 '!'"当判据：这台 `Anysphere.Cursor` / `ai.opencode.desktop` /
        // `ai.verdent.deck` 三颗的 AppID 就是这样（`Get-StartApps` 报的一模一样），
        // 要求带 '!' 会把三颗能启动的应用挡在门外。
        // 但 `Microsoft.AutoGenerated.{GUID}` 那一族必须拒：那是开始菜单里普通 .lnk
        // 在 AppsFolder 里的镜像（这台混进来的就是"Uninstall CMake"、"任务管理器"、
        // "Hyper-V 管理器"这些），收进来等于给同一份索引收第二遍。
        const bool autoGenerated = a.launchPath.startsWith(QStringLiteral("Microsoft.AutoGenerated."),
                                                           Qt::CaseInsensitive);
        const QString nameLower = a.name.toLower();
        const bool uninstaller = nameLower.contains(QStringLiteral("uninstall"))
                                 || a.name.startsWith(QStringLiteral("卸载"));
        if (a.name.isEmpty() || !isAumid || autoGenerated || uninstaller) {
            ++rejected;
            item->Release();
            continue;
        }
        a.aumid = a.launchPath;
        a.launchPath = QStringLiteral("shell:AppsFolder\\") + a.aumid;
        iconSourceOf(item, &a.iconSrc, &a.iconIndex);
        out.append(a);
        item->Release();
    }
    Q_UNUSED(seen);
    Q_UNUSED(rejected);
    en->Release();
    root->Release();
    if (weOwnCom)
        CoUninitialize();
    return out;
}

} // namespace Platform
